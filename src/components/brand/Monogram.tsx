export function Monogram({
  concept = "architect",
  className,
  title = "Цветочная База Дубравиных",
}: {
  concept?: MonogramConcept;
  className?: string;
  /** Доступное имя. Пустая строка — знак декоративный. */
  title?: string;
}) {
  const { d, viewBox } = CONCEPTS[concept];

  return (
    <svg
      viewBox={viewBox}
      className={className}
      role={title ? "img" : undefined}
      aria-label={title || undefined}
      aria-hidden={title ? undefined : true}
      fill="currentColor"
    >
      <path d={d} fillRule="evenodd" />
    </svg>
  );
}

