export function Monogram({
  concept = "architect",
  className,
  title = "Цветы Дубравиных",
}: {
  concept?: MonogramConcept;
  className?: string;
  /** Доступное имя. Пустая строка — знак декоративный. */
  title?: string;
}) {
  const meta = CONCEPTS[concept];
  const stroke = meta.render === "stroke";

  return (
    <svg
      viewBox={meta.viewBox}
      className={className}
      role={title ? "img" : undefined}
      aria-label={title || undefined}
      aria-hidden={title ? undefined : true}
      fill={stroke ? "none" : "currentColor"}
    >
      <path
        d={meta.d}
        fillRule={stroke ? undefined : "evenodd"}
        stroke={stroke ? "currentColor" : undefined}
        strokeWidth={stroke ? (concept === "plastic" ? 14 : 16) : undefined}
        strokeLinecap={stroke ? (concept === "plastic" ? "round" : "butt") : undefined}
        strokeLinejoin={stroke ? (concept === "plastic" ? "round" : "miter") : undefined}
      />
    </svg>
  );
}

